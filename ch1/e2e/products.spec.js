import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
async function login(page) {
  await page.goto('/admin/#products');
  await page.locator('#email').fill('admin@mori.demo'); await page.locator('#password').fill('Mori2026!');
  await page.getByRole('button', { name: '登入管理室', exact: true }).click();
  await expect(page.locator('#products-content')).toBeVisible();
}
async function fillProduct(page, name = '測試料理') {
  await page.locator('#product-name').fill(name);
  await page.locator('#product-description').fill('新鮮食材與主廚的心意。');
  await page.locator('#product-price').fill('250');
  await page.locator('#product-category').selectOption('starter');
  await page.locator('#product-photo').setInputFiles('assets/salmon.jpg');
  await expect(page.locator('#product-photo-preview')).toBeVisible();
  await expect(page.locator('#save-product')).toBeEnabled();
}
test('商品完整流程：上傳新增、前台點餐、改價、隱藏、重整、再次上架與刪除', async ({ page, context }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  await login(page);
  await page.screenshot({ path: 'artifacts/products-desktop.png', fullPage: true });
  await page.locator('#add-product').click();
  await fillProduct(page, '料理 <試吃>');
  await page.locator('#save-product').click();
  await expect(page.locator('#product-dialog')).not.toBeVisible();
  await expect(page.locator('.product-row')).toHaveCount(10);
  const customer = await context.newPage(); await customer.goto('/');
  await expect(customer.locator('.dish-card')).toHaveCount(10);
  await customer.locator('#search').fill('<試吃>');
  await expect(customer.locator('.dish-card')).toHaveCount(1);
  await customer.locator('#search').fill('');
  await customer.getByRole('button', { name: '加入料理 <試吃>', exact: true }).click();
  await expect(customer.locator('#dish-description')).toHaveText('新鮮食材與主廚的心意。');
  expect(await customer.locator('#dish-image').getAttribute('src')).toMatch(/^data:image\/jpeg/);
  await customer.locator('#dish-form button[type=submit]').click();
  await expect(customer.locator('#total')).toHaveText('NT$ 275');
  await page.getByRole('button', { name: '編輯料理 <試吃>', exact: true }).click();
  await page.locator('#product-price').fill('300');
  await page.locator('#save-product').click();
  await expect(customer.locator('#total')).toHaveText('NT$ 330');
  await page.getByRole('switch', { name: '料理 <試吃>的菜單呈現', exact: true }).click();
  await expect(customer.locator('.dish-card')).toHaveCount(9);
  await expect(customer.locator('#cart-count')).toHaveText('0');
  await page.reload();
  await expect(page.getByRole('switch', { name: '料理 <試吃>的菜單呈現', exact: true })).toHaveAttribute('aria-checked', 'false');
  await page.locator('#product-status').selectOption('hidden');
  await expect(page.locator('.product-row')).toHaveCount(1);
  await page.getByRole('switch', { name: '料理 <試吃>的菜單呈現', exact: true }).click();
  await expect(customer.locator('.dish-card')).toHaveCount(10);
  await page.locator('#product-status').selectOption('all');
  await page.getByRole('button', { name: '刪除料理 <試吃>', exact: true }).click();
  await page.locator('#cancel-delete').click();
  await expect(page.locator('.product-row')).toHaveCount(10);
  await page.getByRole('button', { name: '刪除料理 <試吃>', exact: true }).click();
  await page.locator('#confirm-delete').click();
  await expect(customer.locator('.dish-card')).toHaveCount(9);
  await page.reload(); await expect(page.locator('.product-row')).toHaveCount(9);
  expect(errors).toEqual([]);
});

test('其他分頁更新時避免覆寫舊編輯，工作階段到期關閉商品表單', async ({ page, context }) => {
  await login(page);
  await page.getByRole('button', { name: '編輯炭烤美國肋眼牛排', exact: true }).click();
  const other = await context.newPage(); await login(other);
  await other.getByRole('switch', { name: '炭烤美國肋眼牛排的菜單呈現', exact: true }).click();
  await page.locator('#product-price').fill('1200');
  await page.locator('#save-product').click();
  await expect(page.locator('#product-form-error')).toContainText('其他分頁變更');
  await page.evaluate(() => { const value = JSON.parse(sessionStorage.getItem('mori-admin-demo-session')); value.expiresAt = Date.now() - 1; sessionStorage.setItem('mori-admin-demo-session', JSON.stringify(value)); });
  await page.reload();
  await expect(page.locator('#dashboard-view')).toBeHidden();
  await expect(page.locator('#product-dialog')).not.toBeVisible();
});

test('空菜單不恢復示意商品，損壞儲存不被管理操作覆寫', async ({ page }) => {
  await login(page);
  await page.evaluate(() => localStorage.setItem('mori-catalog-v1', JSON.stringify({ version: 1, items: [] })));
  await page.reload();
  await expect(page.locator('.products-empty')).toBeVisible();
  await page.goto('/');
  await expect(page.locator('.dish-card')).toHaveCount(0);
  await page.goto('/admin/#products');
  await page.evaluate(() => localStorage.setItem('mori-catalog-v1', '{broken'));
  await page.reload();
  await expect(page.locator('#catalog-error')).toContainText('商品資料無法讀取');
  await page.locator('#add-product').click();
  await expect(page.locator('#product-dialog')).not.toBeVisible();
  expect(await page.evaluate(() => localStorage.getItem('mori-catalog-v1'))).toBe('{broken');
});
test('商品驗證：必填、負數、非整數、不合法及過大圖片、取消與儲存失敗', async ({ page }) => {
  await login(page); await page.locator('#add-product').click();
  await page.locator('#save-product').click();
  await expect(page.locator('#product-form-error')).toContainText('商品名稱');
  await page.locator('#product-photo').setInputFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('bad') });
  await expect(page.locator('#photo-error')).toContainText('JPG');
  await page.locator('#product-photo').setInputFiles({ name: 'bad.jpg', mimeType: 'image/jpeg', buffer: Buffer.from('bad') });
  await expect(page.locator('#photo-error')).toContainText('無法讀取照片');
  await page.locator('#product-photo').setInputFiles({ name: 'large.png', mimeType: 'image/png', buffer: Buffer.alloc(5 * 1024 * 1024 + 1) });
  await expect(page.locator('#photo-error')).toContainText('5 MB');
  await fillProduct(page);
  await page.locator('#product-price').fill('-1'); await page.locator('#save-product').click();
  await expect(page.locator('#product-form-error')).toContainText('整數價格');
  await page.locator('#product-price').fill('1.5'); await page.locator('#save-product').click();
  await expect(page.locator('#product-form-error')).toContainText('整數價格');
  await page.locator('#product-price').fill('250');
  await page.evaluate(() => { const original = Storage.prototype.setItem; Storage.prototype.setItem = function(key, value) { if (key === 'mori-catalog-v1') throw new DOMException('Quota', 'QuotaExceededError'); return original.call(this, key, value); }; });
  await page.locator('#save-product').click();
  await expect(page.locator('#product-form-error')).toContainText('儲存失敗');
  await expect(page.locator('.product-row')).toHaveCount(9);
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.reload(); await expect(page.locator('.product-row')).toHaveCount(9);
});
