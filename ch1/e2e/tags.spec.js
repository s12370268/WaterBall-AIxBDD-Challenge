import { test, expect } from '@playwright/test';

test('後台標籤：既有值帶入、自訂、新商品、清空與前台同步', async ({ page, context }) => {
  await page.goto('/admin/#products');
  await page.locator('#email').fill('admin@mori.demo');
  await page.locator('#password').fill('Mori2026!');
  await page.getByRole('button', { name: '登入管理室', exact: true }).click();
  const row = page.locator('.product-row').filter({ hasText: '白桃烏龍氣泡飲' });
  await expect(row.locator('.product-tag')).toHaveText('無酒精');
  await row.getByRole('button', { name: '編輯白桃烏龍氣泡飲', exact: true }).click();
  await expect(page.locator('#product-tag')).toHaveValue('無酒精');
  await expect(page.locator('#product-tag')).toHaveAttribute('maxlength', '20');
  await page.locator('#product-tag').fill('  季節限定  ');
  await page.locator('#save-product').click();
  await expect(row.locator('.product-tag')).toHaveText('季節限定');
  const customer = await context.newPage();
  await customer.goto('/');
  const card = customer.locator('.dish-card').filter({ hasText: '白桃烏龍氣泡飲' });
  await expect(card.locator('.card-tag')).toHaveText('季節限定');
  await page.reload();
  await row.getByRole('button', { name: '編輯白桃烏龍氣泡飲', exact: true }).click();
  await expect(page.locator('#product-tag')).toHaveValue('季節限定');
  await page.locator('#product-tag').fill('<限定>');
  await page.locator('#save-product').click();
  await expect(card.locator('.card-tag')).toHaveText('<限定>');
  await expect(row.locator('.product-tag')).toHaveText('<限定>');
  await row.getByRole('button', { name: '編輯白桃烏龍氣泡飲', exact: true }).click();
  await page.locator('#product-tag').fill('');
  await page.locator('#save-product').click();
  await expect(card.locator('.card-tag')).toHaveCount(0);
  await expect(row.locator('.product-tag')).toHaveCount(0);
  await customer.reload();
  await expect(card.locator('.card-tag')).toHaveCount(0);
  await page.locator('#add-product').click();
  await expect(page.locator('#product-tag')).toHaveValue('');
  await page.locator('#product-name').fill('限定甜點');
  await page.locator('#product-price').fill('180');
  await page.locator('#product-description').fill('每日手作的甜蜜滋味。');
  await page.locator('#product-tag').fill('人氣必點');
  await page.locator('#product-photo').setInputFiles('assets/tiramisu.jpg');
  await expect(page.locator('#save-product')).toBeEnabled();
  await page.locator('#save-product').click();
  const newCard = customer.locator('.dish-card').filter({ hasText: '限定甜點' });
  await expect(newCard.locator('.card-tag')).toHaveText('人氣必點');
  await expect(newCard.locator('.card-tag')).toHaveClass(/popular/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: '編輯限定甜點', exact: true }).click();
  await page.locator('#product-tag').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'artifacts/product-tag-mobile.png' });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
